#!/usr/bin/env python3
"""Fresh, outcome-blind kEfi pre-entry lead-time shadow.

Consumes only closed source partitions after its immutable boundary. It uses
decoder cache files already generated by the existing control worker, so it
does not add a second full source scan. Non-teacher events are scored before
their own state update; teacher events are never scored as signals and are
only used later as finalized labels. A continuity change blocks the lane.
"""
from __future__ import annotations
import argparse, hashlib, json, math, os, sqlite3, subprocess, time
from collections import defaultdict, deque
from datetime import datetime, timezone
from pathlib import Path

WINDOWS=(5,20,60)

def sha(p: Path) -> str:
 h=hashlib.sha256()
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1<<20),b''):h.update(b)
 return h.hexdigest()
def atomic(p:Path,v:dict):
 p.parent.mkdir(parents=True,exist_ok=True); t=p.with_suffix(p.suffix+'.tmp');t.write_text(json.dumps(v,indent=2,sort_keys=True)+'\n');os.replace(t,p)
def utc(): return datetime.now(timezone.utc).isoformat().replace('+00:00','Z')
def epoch(v:str)->int: return int(datetime.fromisoformat(v.replace('Z','+00:00')).timestamp()*1_000_000_000)
def sig(row): return str(row.get('candidate_signature') or row.get('signature'))
def key(row): return (int(row['received_at_unix_ns']),int(row.get('slot',0)),sig(row),int(row.get('event_index',0)))
def logistic(v): return 1/(1+math.exp(-max(-60,min(60,v))))
def fee(r): return float(r.get('lp_fee_bps',0))+float(r.get('protocol_fee_bps',0))+float(r.get('coin_creator_bps',0))

class State:
 def __init__(self): self.events=deque();self.first=None;self.last=None;self.last_quote=None
 def snapshot(self,t,r):
  while self.events and self.events[0][0]<t-60_000_000_000:self.events.popleft()
  q=float(r.get('pool_quote_raw',0) or 0)-float(r.get('pool_quote_delta',0) or 0); b=float(r.get('pool_base_raw',0) or 0)+float(r.get('base_amount',0) or 0)
  prev=self.last
  x=[math.log1p(max(q,0)),math.log1p(max(b,0)),fee(r),math.log1p(min((t-self.first)/1e9 if self.first else 0,86400)),math.log1p(min((t-prev)/1e9 if prev else 86400,86400)),0 if not self.last_quote or q<=0 else math.log1p(q)-math.log1p(self.last_quote)]
  for n in WINDOWS:x.append(math.log1p(sum(1 for a,_ in self.events if a>=t-n*1_000_000_000)))
  for n in WINDOWS:x.append(math.log1p(sum(v for a,v in self.events if a>=t-n*1_000_000_000)))
  x.append(1.0 if prev is None else 0.0); return x
 def observe(self,t,r):
  if self.first is None:self.first=t
  self.events.append((t,float(r.get('user_quote_amount',0) or 0))); self.last=t
  q=float(r.get('pool_quote_raw',0) or 0)-float(r.get('pool_quote_delta',0) or 0)
  if q>0:self.last_quote=q
 def dump(self): return {'events':list(self.events),'first':self.first,'last':self.last,'last_quote':self.last_quote}
 @classmethod
 def load(cls,v):
  s=cls();s.events=deque((int(a),float(b)) for a,b in v.get('events',[]));s.first=v.get('first');s.last=v.get('last');s.last_quote=v.get('last_quote');return s

def score(x,m):
 z=[(v-a)/b for v,a,b in zip(x,m['standardization_means'],m['standardization_scales'])]
 return logistic(float(m['intercept'])+sum(float(m['coefficients'][name])*v for name,v in zip(m['features'],z)))

def closed(root):
 out=[]
 for p in (root/'source-spool/partitions').rglob('manifest.json'):
  try:
   m=json.loads(p.read_text())
   if m.get('temporalHourClosed') is True:out.append(p.parent.relative_to(root/'source-spool/partitions').as_posix())
  except Exception: pass
 return sorted(out)
def cache_path(cache:Path,partition:str): return cache/('decoded-'+partition.replace('/','-')+'.jsonl')
def partition_end(partition: str) -> int:
    return int((datetime.strptime(partition,'%Y/%m/%d/%H').replace(tzinfo=timezone.utc).timestamp()+3600)*1_000_000_000)
def fallback_decode(root: Path, out: Path, partition: str) -> Path:
    """Decode one closed fresh partition only when the shared cache is late."""
    folder=out/'decoder-fallback'; folder.mkdir(parents=True,exist_ok=True)
    decoded=folder/(partition.replace('/','-')+'.jsonl'); summary=decoded.with_suffix('.summary.json'); empty=folder/'empty.jsonl'
    if not decoded.exists():
        empty.write_text('')
        partial=decoded.with_suffix(decoded.suffix+'.partial')
        partial_summary=summary.with_suffix(summary.suffix+'.partial')
        partial.unlink(missing_ok=True); partial_summary.unlink(missing_ok=True)
        subprocess.run(['/usr/bin/ionice','-c3','/root/kefi-work/bin/kefi_prospective_discovery_v5','--candidates',str(root),str(empty),str(partial),str(partial_summary),partition],check=True)
        os.replace(partial,decoded)
        if partial_summary.exists(): os.replace(partial_summary,summary)
    return decoded
def finalized_teachers(root):
 db=root/'finalizer.sqlite3'; final=set()
 try:
  with sqlite3.connect('file:'+str(db)+'?mode=ro',uri=True) as c: final={r[0] for r in c.execute("select signature from finalized_candidate where status='FINALIZED_CANONICAL'")}
 except sqlite3.Error: return set()
 return final
def direct_teachers(root: Path, out: Path, partition: str) -> list[dict]:
    """Canonical direct kEfi PumpSwap BUY records for one closed partition."""
    folder=out/'teacher-discovery'; folder.mkdir(parents=True,exist_ok=True)
    rows=folder/(partition.replace('/','-')+'.jsonl'); summary=rows.with_suffix('.summary.json')
    if not rows.exists():
        partial=rows.with_suffix(rows.suffix+'.partial')
        partial_summary=summary.with_suffix(summary.suffix+'.partial')
        partial.unlink(missing_ok=True); partial_summary.unlink(missing_ok=True)
        subprocess.run(['/usr/bin/ionice','-c3','/root/kefi-work/bin/kefi_prospective_discovery_v5','--discover',str(root),str(partial),str(partial_summary),partition],check=True)
        os.replace(partial,rows)
        if partial_summary.exists(): os.replace(partial_summary,summary)
    with rows.open() as handle:
        return [json.loads(line) for line in handle if line.strip()]

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,required=True);ap.add_argument('--cache',type=Path,required=True);ap.add_argument('--fingerprint',type=Path,required=True);ap.add_argument('--out',type=Path,required=True);ap.add_argument('--boundary',required=True);ap.add_argument('--cache-fallback-delay-seconds',type=int,default=300);ns=ap.parse_args()
 model=json.loads(ns.fingerprint.read_text()); boundary=epoch(ns.boundary)
 if model.get('status')!='FROZEN_FOR_PROSPECTIVE_OUTCOME_BLIND_SHADOW' or not model.get('strict_preentry'):raise SystemExit('FAIL_CLOSED: invalid frozen fingerprint')
 start_health=json.loads((ns.root/'health.json').read_text()); baseline={'epoch':start_health.get('currentEpoch'),'gaps':start_health.get('continuityGaps'),'reconnects':start_health.get('reconnects')}
 boundary_receipt=ns.out/'boundary.json'
 if not boundary_receipt.exists():atomic(boundary_receipt,{'schema':'KEFI_RICH_PREENTRY_SHADOW_BOUNDARY_V2','boundary_utc':ns.boundary,'fingerprint_sha256':sha(ns.fingerprint),'source_health_baseline':baseline,'warmup_seconds':model['warmup_seconds'],'lead_windows_seconds':model['lead_windows_seconds'],'minimum_finalized_teacher_labels':model['minimum_finalized_teacher_labels'],'minimum_fresh_complete_scored_market_events':model['minimum_fresh_complete_scored_market_events'],'outcomes_accessed':False,'pnl_accessed':False,'execution_enabled':False})
 statep=ns.out/'state.json'; state=json.loads(statep.read_text()) if statep.exists() else {'processed':[],'pools':{},'labels':[],'signals':[],'scored_market_events':0,'score_matches':0}
 pools=defaultdict(State,{k:State.load(v) for k,v in state.get('pools',{}).items()}); processed=set(state.get('processed',[])); warmup=boundary+int(model['warmup_seconds']*1e9)
 while True:
  h=json.loads((ns.root/'health.json').read_text())
  if h.get('continuityGaps')!=baseline['gaps'] or h.get('currentEpoch')!=baseline['epoch']:
   atomic(ns.out/'blocked.json',{'status':'FAILED_CLOSED_CONTINUITY_CHANGE','at_utc':utc(),'baseline':baseline,'current':{'epoch':h.get('currentEpoch'),'gaps':h.get('continuityGaps'),'reconnects':h.get('reconnects')}});return
  final=finalized_teachers(ns.root)
  for label in state['labels']:
   label['finalized']=label['signature'] in final
  for partition in closed(ns.root):
   if partition in processed: continue
   # Historical partitions ending at or before the prospective boundary are
   # categorically outside this run, including its warm-up state.
   if partition_end(partition) <= boundary:
    processed.add(partition)
    state['processed']=sorted(processed)
    atomic(statep,state)
    continue
   cached=cache_path(ns.cache,partition); fallback=False
   if not cached.exists():
    if time.time_ns() < partition_end(partition)+ns.cache_fallback_delay_seconds*1_000_000_000: continue
    cached=fallback_decode(ns.root,ns.out,partition); fallback=True
   teacher_rows=direct_teachers(ns.root,ns.out,partition)
   teacher_ids={(str(row['signature']),int(row.get('event_index',0))) for row in teacher_rows}
   rows=[]; previous=None
   with cached.open() as f:
    for line in f:
     if not line.strip():continue
     r=json.loads(line); k=key(r)
     if previous is not None and k<previous:raise RuntimeError('FAIL_CLOSED: cached decoder order regression')
     previous=k
     if k[0]>=boundary:rows.append(r)
   if not rows: processed.add(partition);continue
   for r in rows:
    t=int(r['received_at_unix_ns']); pool=str(r['pool']); mint=str(r.get('mint','')); s=sig(r); st=pools[pool]; x=st.snapshot(t,r)
    is_teacher=(s,int(r.get('event_index',0))) in teacher_ids
    if t>=warmup:
     if is_teacher:
      prior=[z for z in state['signals'] if z['pool']==pool and 0<t-z['received_at_unix_ns']<=20_000_000_000]
      state['labels'].append({'signature':s,'pool':pool,'mint':mint,'received_at_unix_ns':t,'prior_signal_5s':sum(t-z['received_at_unix_ns']<=5_000_000_000 for z in prior),'prior_signal_10s':sum(t-z['received_at_unix_ns']<=10_000_000_000 for z in prior),'prior_signal_20s':len(prior),'finalized':s in final})
     else:
      state['scored_market_events']+=1
      value=score(x,model)
      if value>=float(model['threshold']):
       state['score_matches']+=1
       state['signals'].append({'signature':s,'pool':pool,'mint':mint,'received_at_unix_ns':t,'score':value})
    st.observe(t,r)
   processed.add(partition)
   # Retain only possible lead signals; artifacts are append-safe snapshots, not raw source.
   latest=max(int(r['received_at_unix_ns']) for r in rows); state['signals']=[z for z in state['signals'] if latest-z['received_at_unix_ns']<=20_000_000_000]
   missing_teachers=teacher_ids-{(sig(r),int(r.get('event_index',0))) for r in rows}
   if missing_teachers:
    atomic(ns.out/'unreconciled-teacher-events.json',{'status':'FAIL_CLOSED_UNRECONCILED_TEACHER_EVENTS','partition':partition,'count':len(missing_teachers),'identities':sorted(f'{s}:{i}' for s,i in missing_teachers)})
    return
   state['processed']=sorted(processed);state['pools']={k:v.dump() for k,v in pools.items() if v.last and latest-v.last<=3_600_000_000}
   atomic(statep,state)
   finalized_labels=[x for x in state['labels'] if x.get('finalized')]
   summary={'schema':'KEFI_RICH_PREENTRY_SHADOW_CHECKPOINT_V2','status':'RUNNING','updated_at_utc':utc(),'boundary_utc':ns.boundary,'processed_partitions':state['processed'],'finalized_teacher_labels':len(finalized_labels),'teacher_labels_with_prior_signal_5s':sum(x['prior_signal_5s']>0 for x in finalized_labels),'teacher_labels_with_prior_signal_10s':sum(x['prior_signal_10s']>0 for x in finalized_labels),'teacher_labels_with_prior_signal_20s':sum(x['prior_signal_20s']>0 for x in finalized_labels),'fresh_complete_scored_market_events':state['scored_market_events'],'score_matches':state['score_matches'],'frozen_fingerprint_sha256':sha(ns.fingerprint),'outcomes_accessed':False,'pnl_accessed':False,'execution_enabled':False}
   atomic(ns.out/'checkpoint.json',summary)
   if fallback:
    cached.unlink(missing_ok=True); cached.with_suffix('.summary.json').unlink(missing_ok=True)
  time.sleep(60)
if __name__=='__main__':main()
